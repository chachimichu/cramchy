const assert=require('node:assert/strict');
require('../js/quick-gwa-rules.js');
const rules=globalThis.CramchyModules.quickGwaRules;
const calc=rows=>rules.compute(rows);
const msg=(rows,name='Chachi')=>rules.formatMessage(calc(rows),name);
const both=msg([{grade:'2.0',units:3},{grade:'3.0',units:3}]);
assert.match(both,/Chachi, you didn’t qualify/);
assert.match(both,/subject grades was below 2.5/);
assert.match(both,/GWA of 2.50 was below the required 3.25/);
const lowGwa=msg([{grade:'3.0',units:3},{grade:'3.0',units:3}]);
assert.match(lowGwa,/GWA of 3.00 was below the required 3.25/);
assert.doesNotMatch(lowGwa,/below 2.5/);
const lowSubject=msg([{grade:'2.0',units:1},{grade:'4.0',units:9}]);
assert.match(lowSubject,/subject grades was below 2.5/);
assert.doesNotMatch(lowSubject,/below the required 3.25/);
assert.match(msg([{grade:'3.5',units:3},{grade:'3.5',units:3}]),/Chachi, you did it!.*First Honors/);
assert.match(msg([{grade:'3.5',units:3},{grade:'3.0',units:3}]),/Second Honors/);
assert.match(rules.formatMessage(calc([{grade:'3.5',units:3},{grade:'3.5',units:3}]),''),/^you did it!/);
assert.match(msg([{grade:'3.5',units:3},{grade:'INC',units:3}]),/INC grade needs review/);
console.log('Quick GWA messages: personalized qualification, low-GWA, low-subject-grade, combined blockers, honors tiers, fallback name, and special-grade guidance passed.');
